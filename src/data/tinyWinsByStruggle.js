/** The 30 wins curated for one struggle, in order. */
export function challengesForStruggle(struggle) {
  return STRUGGLE_CHALLENGES.filter(c => c.struggle === struggle);
}

/**
 * Day 1..30 of someone's struggle set, narrowed to their work mode where
 * possible. Falls back to the unnarrowed set rather than returning nothing.
 */
export function challengeForDay(struggle, dayNumber, workMode = 'custom') {
  const all = challengesForStruggle(struggle);
  if (!all.length) return null;
  const fitted = all.filter(c => c.workModes.includes(workMode));
  const list = fitted.length >= 10 ? fitted : all;
  const i = ((dayNumber - 1) % list.length + list.length) % list.length;
  return list[i];
}

export default STRUGGLE_CHALLENGES;
